import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const repoRoot = process.cwd();
const readmePath = path.join(repoRoot, "README.md");
const catalogPath = path.join(repoRoot, "docs", "catalog.md");
const skillsDir = path.join(repoRoot, "claude-code-arsenal", "skills");
const agentsDir = path.join(repoRoot, "claude-code-arsenal", "agents");

const START = "<!-- CATALOG:START -->";
const END = "<!-- CATALOG:END -->";

/**
 * Minimal YAML frontmatter parser that handles:
 *   - Simple scalar:  key: value
 *   - Block scalars:  key: >   key: >-   key: |
 *   - Quoted values:  key: "value"
 */
const parseFrontmatter = (content) => {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};

  const lines = match[1].split(/\r?\n/);
  const data = {};
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];
    const colonIdx = line.indexOf(":");
    if (colonIdx === -1 || line.startsWith(" ") || line.startsWith("\t")) {
      i++;
      continue;
    }

    const key = line.slice(0, colonIdx).trim();
    const rest = line.slice(colonIdx + 1).trim();

    // Block scalar: > >- | |-
    if (/^[>|][-]?$/.test(rest)) {
      const parts = [];
      i++;
      while (i < lines.length) {
        const next = lines[i];
        if (next.startsWith("  ") || next.startsWith("\t")) {
          parts.push(next.trim());
          i++;
        } else {
          break;
        }
      }
      data[key] = parts.join(" ").trim();
      continue;
    }

    data[key] = rest.replace(/^["']|["']$/g, "");
    i++;
  }

  return data;
};

const mdEscape = (text) => text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();

const buildRows = async (dir, ext) => {
  const entries = await readdir(dir, { withFileTypes: true });
  const rows = [];

  for (const entry of entries) {
    if (entry.isDirectory()) {
      const filePath = path.join(dir, entry.name, "SKILL.md");
      try {
        const content = await readFile(filePath, "utf8");
        const fm = parseFrontmatter(content);
        const name = fm.name || entry.name;
        const description = fm.description || "Sin descripcion.";
        rows.push({ name, description });
      } catch {
        rows.push({ name: entry.name, description: "Sin descripcion." });
      }
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(ext)) {
      const filePath = path.join(dir, entry.name);
      const content = await readFile(filePath, "utf8");
      const fm = parseFrontmatter(content);
      const name = fm.name || entry.name.replace(ext, "");
      const description = fm.description || "Sin descripcion.";
      rows.push({ name, description });
    }
  }

  return rows.sort((a, b) => a.name.localeCompare(b.name));
};

const toTable = (items) => {
  const header = "| Name / Nombre | What it does / Para que sirve |\n| --- | --- |";
  const body = items
    .map((item) => `| \`${mdEscape(item.name)}\` | ${mdEscape(item.description)} |`)
    .join("\n");
  return `${header}\n${body}`;
};

const skills = await buildRows(skillsDir, ".md");
const agents = await buildRows(agentsDir, ".md");

// --- Write full catalog to docs/catalog.md ---
await mkdir(path.join(repoRoot, "docs"), { recursive: true });
const catalogContent = [
  "# Full Catalog / Catalogo completo",
  "",
  "> Auto-generated by `scripts/generate-readme-catalog.mjs`. Do not edit manually.",
  "",
  `## ${skills.length} skills · ${agents.length} agents`,
  "",
  "---",
  "",
  "## Skills",
  "",
  toTable(skills),
  "",
  "---",
  "",
  "## Agents / Agentes",
  "",
  toTable(agents),
  "",
].join("\n");

await writeFile(catalogPath, catalogContent, "utf8");

// --- Write short summary section to README between markers ---
const readmeSection = [
  START,
  "## Catalog / Catalogo",
  "",
  `**${skills.length} skills · ${agents.length} agents** — [Browse the full catalog →](./docs/catalog.md)`,
  "",
  "### Featured skills",
  "",
  "| Name | What it does |",
  "| --- | --- |",
  "| `ads` | Full-stack paid advertising audit across 7 platforms with 225+ checks |",
  "| `ui-ux-pro-max` | UI/UX design with 50+ styles, 161 palettes, and 10 stacks |",
  "| `tdd-workflow` | Enforces test-first development with 80%+ coverage |",
  "| `deep-research` | Multi-source research via Firecrawl + Exa with citations |",
  "| `systematic-debugging` | Structured bug triage before proposing any fix |",
  "| `make-plan` | Phased implementation plan with documentation discovery |",
  "| `agentic-engineering` | Eval-first execution with cost-aware model routing |",
  "| `codebase-onboarding` | Generates architecture map + CLAUDE.md for any repo |",
  "| `content-engine` | Native content for X, LinkedIn, TikTok, YouTube, newsletters |",
  "| `security-review` | OWASP Top 10 checklist for auth, input, APIs, and secrets |",
  "",
  END,
].join("\n");

const readme = await readFile(readmePath, "utf8");

let next;
if (readme.includes(START) && readme.includes(END)) {
  next = readme.replace(new RegExp(`${START}[\\s\\S]*?${END}`), readmeSection);
} else {
  next = `${readme}\n\n${readmeSection}\n`;
}

await writeFile(readmePath, next, "utf8");
console.log(`Catalog updated. Skills: ${skills.length}. Agents: ${agents.length}. docs/catalog.md written.`);
